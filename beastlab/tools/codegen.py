#!/usr/bin/env python3
"""Generate src/BeastLab/Generated/Sheets.g.cs: one record struct per sheet, one value per row,
plus an Ids class per sheet so the code refers to rows by compile-checked names."""
import json

from sheetlib import SRC, load_all, pascal

CS_TYPES = {"string": "string", "enum": "string", "int": "int", "float": "float", "bool": "bool",
            "string[]": "string[]"}


def lit(kind, v):
    if kind in ("string", "enum"):
        return json.dumps(v)
    if kind == "string[]":
        return "new string[] { " + ", ".join(json.dumps(x) for x in v) + " }"
    if kind == "bool":
        return "true" if v else "false"
    if kind == "int":
        return str(v)
    if kind == "float":
        return f"{float(v)!r}f"
    raise ValueError(kind)


CS_KEYWORDS = {"volatile", "default", "base", "class", "event", "object", "string", "fixed", "lock", "params",
               "out", "ref", "in", "is", "as", "new", "case", "checked", "const", "operator", "void", "none_"}

IDS = {"hooks": "HookIds", "columns_dltb": "DltbColumnIds", "dltb_sources": "DltbSourceIds",
       "systems": "SystemIds", "hud": "HudIds"}


def ids_class(name):
    return IDS.get(name, pascal(name) + "Ids")


def main():
    out = ["// <auto-generated> from sheets/*.json by tools/codegen.py. Edit the sheets, not this file.",
           "#nullable disable", "namespace BeastLab.Generated", "{"]
    tables = []
    for name, sheet in load_all().items():
        struct = sheet["struct"]
        cols = sheet["columns"]
        params = ", ".join(f"{CS_TYPES[c['type']]} {pascal(k)}" for k, c in cols.items())
        out.append(f"    /// <summary>{sheet.get('doc', '')}</summary>")
        out.append(f"    public sealed record {struct}({params});")
        ids_cls = ids_class(name)
        out.append(f"    public static class {ids_cls}")
        out.append("    {")
        for row in sheet["rows"]:
            ident = row["id"].replace(".", "_")
            if ident in CS_KEYWORDS:
                ident = "@" + ident
            out.append(f"        public const string {ident} = {json.dumps(row['id'])};")
        out.append("    }")
        rows = []
        for row in sheet["rows"]:
            rows.append(f"            new {struct}(" + ", ".join(lit(c["type"], row[k]) for k, c in cols.items()) + "),")
        tables.append((pascal(name), struct, rows))
    out.append("    public static class Sheets")
    out.append("    {")
    for prop, struct, rows in tables:
        out.append(f"        public static readonly {struct}[] {prop} = new {struct}[]")
        out.append("        {")
        out.extend(rows)
        out.append("        };")
    out.append("    }")
    out.append("}")
    target = SRC / "Generated" / "Sheets.g.cs"
    target.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {target.relative_to(SRC.parent.parent)}")


if __name__ == "__main__":
    main()
